// Create browser selection using switch.

let browser = "Chrome";

switch (browser)
{
    case "Chrome" : 
        console.log("Google Chrome Selected!");
        break;
    case "Firefox" : 
        console.log("Mozilla Firefox Selected!");
        break;
    case "Safari" : 
        console.log("Safari Webkit Selected!");
        break;
    default :
        console.log("Unknown Browser");
}