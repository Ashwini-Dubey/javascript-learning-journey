const studentGrade = 40;

if (studentGrade >= 90) {
    console.log("You got an A!");
} 
else if (studentGrade >= 75 && studentGrade < 90) {
    console.log("You got a B!");
} 
else if (studentGrade >= 60 && studentGrade < 75) {
    console.log("You got a C!");
}  
else {
    console.log("You got an F!");
}