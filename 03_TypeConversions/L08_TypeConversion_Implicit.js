/*
Implicit Type Conversion (Coercion) :
In JavaScript, implicit type conversion, also known as coercion, occurs when the language automatically converts one data type to another during an operation. This can lead to unexpected results if not understood properly.
*/

//String + Number Coercion
let result = "5" + 2;
console.log(result);  

//String - Number Coercion
let score = "10" -2;
console.log(score);

//Boolean Coercion
console.log(5+true);
console.log(5+false); 