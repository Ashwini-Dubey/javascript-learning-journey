// Operators in Javascript

/*
Arithmentic Operators:
1. + (Addition)
2. - (Subtraction)
3. * (Multiplication)
4. / (Division)
5. % (Modulus)
6. ** (Exponentiation)
*/

let a = 5;
let b = 2;

console.log("Addition :",a + b); // This will print the result of addition of a and b.
console.log("Subtraction :",a - b); // This will print the result of subtraction of a and b.
console.log("Multiplication :",a * b); // This will print the result of multiplication of a and b.
console.log("Division :",a / b); // This will print the result of division of a and b.
console.log("Modulus :",a % b); // This will print the result of modulus of a and b.
console.log("Exponentiation :",a ** b); // This will print the result of exponentiation of a to the power of b.







