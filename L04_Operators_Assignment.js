/*
Assignment Operators:
1. = (Assignment)
2. += (Addition Assignment)
3. -= (Subtraction Assignment)
4. *= (Multiplication Assignment)
5. /= (Division Assignment)
6. %= (Modulus Assignment)
7. **= (Exponentiation Assignment)
*/

console.log("Assignment:",c=5)
console.log("Addition Assignment:",c+=2) // This will add 2 to the current value of c and assign the result back to c.
console.log("Subtraction Assignment:",c-=2) // This will subtract 2 from the current value of c and assign the result back to c.
console.log("Multiplication Assignment:",c*=2) // This will multiply the current value of c by 2 and assign the result back to c.
console.log("Division Assignment:",c/=2) // This will divide the current value of c by 2 and assign the result back to c.
console.log("Modulus:",c%=2) // This will calculate the modulus of the current value of c by 2 and assign the result back to c.
console.log("Exponentiation:",c**=2) // This will raise the current value of c to the power of 2 and assign the result back to c.