/*
The Spread Operator (...) allows you to expand (spread) the elements of an array or the properties of an object into another array, object, or function call.

The symbol for the spread operator is:

...

Think of it as unpacking the contents of an array or object.
*/

const numbers = [10, 20, 30];

console.log(numbers); // Output: [10, 20, 30]

console.log(...numbers); // Output: 10 20 30